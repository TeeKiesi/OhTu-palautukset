    def test_viitegeneraattori_luo_uuden_viitteen(self):

        self.viitegeneraattori_mock2 = Viitegeneraattori()
        self.kauppa = Kauppa(
            self.varasto_mock,
            self.pankki_mock,
            self.viitegeneraattori_mock2,
            )
        # tehdään ostokset
        
        self.kauppa.aloita_asiointi()
        self.kauppa.tilimaksu("pekka", "12345")
        self.kauppa.aloita_asiointi()
        self.kauppa.tilimaksu("pekka", "12345")
        # varmistetaan, että metodia tilisiirto on kutsuttu
        self.pankki_mock.tilisiirto.assert_called_with("pekka", 3, "12345", "33333-44455", 0)

